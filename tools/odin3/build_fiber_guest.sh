#!/usr/bin/env bash
# Build the guest libSceFiber (src/core/libraries/fiber/fiber_guest.c) into fiber_guest.inc: x86-64
# code that FEX runs, embedded in the arm64 core. Uses clang and lld from the bachata-build container,
# where /workspace is this repository. Rerun after editing fiber_guest.c and commit both files.
set -Eeuo pipefail
docker exec -w /workspace bachata-build bash -ec '
T=$(mktemp -d)
clang --target=x86_64-unknown-linux-gnu -O2 -ffreestanding -fno-builtin -nostdlib -fPIC \
    -fvisibility=hidden -fno-jump-tables -fno-stack-protector -fno-asynchronous-unwind-tables \
    -fcf-protection=none -Wall -Werror -c src/core/libraries/fiber/fiber_guest.c -o $T/fiber.o
# The code is mapped read-only: refuse anything that needs writable data or relocations at load.
! llvm-readelf -S $T/fiber.o | grep -E "\.(data|bss|got)" >&2
printf "SECTIONS { . = 0; .text : { *(.text .text.*) *(.rodata .rodata.*) } /DISCARD/ : { *(.comment) *(.note*) } }\n" > $T/fiber.ld
ld.lld -static -nostdlib -e 0 -T $T/fiber.ld -o $T/fiber.elf $T/fiber.o
! llvm-readelf -S $T/fiber.elf | grep -E "\.(data|bss|got|rela)" >&2
llvm-objcopy -O binary --only-section=.text $T/fiber.elf $T/fiber.bin
python3 - $T src/core/libraries/fiber/fiber_guest.inc "$(clang --version | head -1)" <<"EOF"
import subprocess, sys
tmp, out, version = sys.argv[1:]
code = open(f"{tmp}/fiber.bin", "rb").read()
syms = {}
for line in subprocess.run(["llvm-nm", "--defined-only", f"{tmp}/fiber.elf"], capture_output=True, text=True, check=True).stdout.splitlines():
    addr, kind, name = line.split()
    if kind in "Tt" and name.startswith("sceFiber"):
        syms[name] = int(addr, 16)
with open(out, "w") as f:
    f.write("// Generated by tools/odin3/build_fiber_guest.sh from fiber_guest.c, do not edit.\n")
    f.write(f"// {version}, x86-64.\n\n#pragma once\n\n")
    f.write(f"inline constexpr std::array<u8, {len(code)}> FiberGuestCode{{\n")
    for i in range(0, len(code), 16):
        f.write("    " + ", ".join(f"0x{b:02x}" for b in code[i:i + 16]) + ",\n")
    f.write("};\n\n")
    for name, addr in sorted(syms.items()):
        f.write(f"inline constexpr u32 FiberGuest_{name} = {addr:#x};\n")
print(f"{len(code)} bytes, {len(syms)} functions")
EOF
rm -rf $T
'
